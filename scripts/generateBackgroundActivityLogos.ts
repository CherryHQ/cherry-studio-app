import { writeFile } from 'node:fs/promises';
import path from 'node:path';

import sharp from 'sharp';

const ROOT = path.resolve(__dirname, '..');
// ExpoUI loads UIImage(data:) at scale 1. A frame only changes layout, not the
// bitmap size. 32px covers the largest logo slot and fits the minimal activity.
const LOGO_SIZE = 32;

async function generateBackgroundActivityLogos() {
  const variants: string[] = [];
  for (const theme of ['dark', 'light'] as const) {
    const png = await sharp(path.join(ROOT, 'assets', `icon-${theme}.png`))
      .resize(LOGO_SIZE, LOGO_SIZE, { fit: 'inside', withoutEnlargement: true })
      .png()
      .toBuffer();
    variants.push(
      `/** ${LOGO_SIZE}px assets/icon-${theme}.png derivative for native widgets and previews. */\n` +
        `export const CHERRY_ACTIVITY_LOGO_${theme.toUpperCase()}_BASE64 =\n` +
        `  '${png.toString('base64')}';\n`,
    );
  }
  await writeFile(
    path.join(ROOT, 'packages/ui/src/background-activity/logo.ts'),
    '// Generated by pnpm exec tsx scripts/generateBackgroundActivityLogos.ts. Do not edit.\n\n' +
      variants.join('\n'),
  );
}

generateBackgroundActivityLogos().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});

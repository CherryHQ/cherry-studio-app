import { parseMermaidPageMessage } from '@cherrystudio/mermaid-webview/protocol';
import { Asset } from 'expo-asset';
import { File } from 'expo-file-system';
import {
  useCallback,
  useEffect,
  useLayoutEffect,
  useMemo,
  useRef,
  useState,
  useSyncExternalStore,
} from 'react';
import { View } from 'react-native';
import { WebView } from 'react-native-webview';
import { withUniwind } from 'uniwind';

import { loggerService } from '@/shared/core/logger/LoggerService';

import { mermaidRenderer, type MermaidRendererPage } from '../utils/mermaidRenderer';

const logger = loggerService.withContext('MermaidRendererHost');
const RendererWebView = withUniwind(WebView);
// Generated by `@cherrystudio/mermaid-webview` on install; see its README.
const PAGE_ASSET = require('@cherrystudio/mermaid-webview/mermaid.html');

/**
 * Mounts the hidden renderer page while diagrams are waiting and for a minute afterwards. Mount it
 * once, before the root navigator, so opaque screens cover it while it stays laid out.
 */
export function MermaidRendererHost() {
  const active = useSyncExternalStore(mermaidRenderer.subscribe, mermaidRenderer.isActive);
  return active ? <RendererPage /> : null;
}

function RendererPage() {
  const [html, setHtml] = useState<string>();
  const [generation, setGeneration] = useState(0);
  const replacePage = useCallback(() => setGeneration((value) => value + 1), []);

  useEffect(() => {
    let live = true;
    // The text is held only while the page is mounted.
    Asset.loadAsync(PAGE_ASSET)
      .then(([page]) => {
        if (!page?.localUri) throw new Error('Mermaid renderer page is unavailable');
        return new File(page.localUri).text();
      })
      .then(
        (text) => {
          if (live) setHtml(text);
        },
        (error: unknown) => {
          if (!live) return;
          logger.warn('Failed to load the Mermaid renderer page', error as Error);
          mermaidRenderer.unavailable();
        },
      );
    return () => {
      live = false;
    };
  }, []);

  if (!html) return null;
  return <RendererPageView key={generation} html={html} onReset={replacePage} />;
}

function RendererPageView({ html, onReset }: { html: string; onReset: () => void }) {
  const webView = useRef<WebView>(null);
  const source = useMemo(() => ({ html }), [html]);
  const [page] = useState<MermaidRendererPage>(() => ({
    send: (request) =>
      webView.current?.injectJavaScript(
        `window.cherryMermaid&&window.cherryMermaid.render(${JSON.stringify(request)});true;`,
      ),
    reset: onReset,
  }));

  useLayoutEffect(() => {
    mermaidRenderer.attach(page);
    return () => mermaidRenderer.detach(page);
  }, [page]);

  const fail = () => mermaidRenderer.fail(page);

  return (
    <View
      accessibilityElementsHidden
      className="absolute top-0 left-0 size-96"
      importantForAccessibility="no-hide-descendants"
      pointerEvents="none"
    >
      <RendererWebView
        ref={webView}
        allowFileAccess={false}
        allowFileAccessFromFileURLs={false}
        allowUniversalAccessFromFileURLs={false}
        incognito
        javaScriptCanOpenWindowsAutomatically={false}
        onContentProcessDidTerminate={fail}
        onError={fail}
        onMessage={({ nativeEvent }) => {
          const message = parseMermaidPageMessage(nativeEvent.data);
          if (message) mermaidRenderer.receive(page, message);
        }}
        onRenderProcessGone={fail}
        onShouldStartLoadWithRequest={({ url, isTopFrame }) =>
          isTopFrame !== false && (url === 'about:blank' || url.startsWith('about:blank#'))
        }
        originWhitelist={['*']}
        scrollEnabled={false}
        setSupportMultipleWindows={false}
        sharedCookiesEnabled={false}
        source={source}
        textZoom={100}
        thirdPartyCookiesEnabled={false}
      />
    </View>
  );
}
